#!/usr/bin/env node
/**
 * M8: lists every container image the release uses (deploy/docker-compose.yml and the Dockerfiles' FROM
 * lines) with the digest it is pinned to, and fails if any is not pinned. Writes docs/release/IMAGE_DIGESTS.md.
 * Images built from this repository (survey-anything/*) are listed separately: their digests exist only once
 * the release images are built and pushed.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCES = ['deploy/docker-compose.yml', 'apps/backend/Dockerfile', 'deploy/gate/Dockerfile'];

export function pinnedImages(root: string): { image: string; usedBy: string[] }[] {
  const seen = new Map<string, Set<string>>();
  for (const f of SOURCES) {
    const text = readFileSync(join(root, f), 'utf8');
    for (const m of text.matchAll(/^\s*(?:image:|FROM)\s+(\S+)/gm)) {
      const image = m[1] ?? '';
      if (image.startsWith('survey-anything/')) continue;
      const users = seen.get(image) ?? new Set<string>();
      users.add(f);
      seen.set(image, users);
    }
  }
  return [...seen.entries()].map(([image, used]) => ({ image, usedBy: [...used].sort() })).sort((a, b) => a.image.localeCompare(b.image));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
  const images = pinnedImages(root);
  const unpinned = images.filter((i) => !/@sha256:[0-9a-f]{64}$/.test(i.image));
  const lines = [
    '# Image digests (draft for the release)',
    '',
    'Generated by `pnpm release:digests`. Every third-party image the deploy stack runs and every base image the',
    'release Dockerfiles build on, with the digest it is pinned to. The images built from this repository',
    '(`survey-anything/backend`, `survey-anything/confirm-gate`) get their digests when the release images are',
    'built and pushed; record them here at that point.',
    '',
    '| Image | Digest | Used by |',
    '|---|---|---|',
    ...images.map((i) => `| \`${i.image.split('@')[0]}\` | \`${i.image.split('@')[1] ?? 'NOT PINNED'}\` | ${i.usedBy.map((u) => `\`${u}\``).join(', ')} |`),
    '',
    '| Built from this repository | Digest |',
    '|---|---|',
    '| `survey-anything/backend` (`apps/backend/Dockerfile`) | recorded at release |',
    '| `survey-anything/confirm-gate` (`deploy/gate/Dockerfile`) | recorded at release |',
    '',
  ];
  writeFileSync(join(root, 'docs', 'release', 'IMAGE_DIGESTS.md'), lines.join('\n'));
  console.info(`docs/release/IMAGE_DIGESTS.md: ${images.length} images${unpinned.length ? `, ${unpinned.length} NOT pinned` : ', all pinned by digest'}`);
  if (unpinned.length) process.exit(1);
}
